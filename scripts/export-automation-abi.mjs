import { mkdir, readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
await mkdir(new URL("packages/shared/abi/", root), { recursive: true });
for (const name of [
  "CommitPassFactory",
  "CommitPassVault",
  "CommitPassAutomation",
]) {
  const compiled = JSON.parse(
    await readFile(
      new URL(`contracts/out/${name}.sol/${name}.json`, root),
      "utf8",
    ),
  );
  await writeFile(
    new URL(`packages/shared/abi/${name}.json`, root),
    JSON.stringify(compiled.abi, null, 2) + "\n",
  );
}
const artifact = JSON.parse(
  await readFile(
    new URL(
      "contracts/out/CommitPassAutomation.sol/CommitPassAutomation.json",
      root,
    ),
    "utf8",
  ),
);
const names = new Set([
  "getBatch",
  "getState",
  "LifecycleRequested",
  "requestStart",
  "requestSettlement",
  "onReport",
]);
const abi = artifact.abi.filter((item) => names.has(item.name));
await writeFile(
  new URL("packages/shared/src/automation-abi.ts", root),
  `// Generated by scripts/export-automation-abi.mjs after forge build.\nexport const automationAbi = ${JSON.stringify(abi, null, 2)} as const;\n`,
);
